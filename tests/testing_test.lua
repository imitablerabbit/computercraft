--[[
Tests for the testing API itself: that the expectations pass and fail
when they should, with useful messages, and that the fake turtle and
stubs behave as documented.
--]]

describe("expect", function()
  it("equal passes on equal values and fails with both values", function()
    expect.equal(1 + 1, 2)
    local err = expect.error(function() expect.equal(3, 4) end)
    expect.contains(err, "expected 4, got 3")
  end)

  it("same compares tables deeply and names the differing path", function()
    expect.same({ a = 1, b = { 1, 2, { c = "x" } } }, { a = 1, b = { 1, 2, { c = "x" } } })
    local err = expect.error(function() expect.same({ b = { 1, 5 } }, { b = { 1, 2 } }) end)
    expect.contains(err, ".b[2]: expected 2, got 5")
    err = expect.error(function() expect.same({ a = 1 }, { a = 1, extra = true }) end)
    expect.contains(err, ".extra: expected true, got nil")
  end)

  it("truthy and falsy", function()
    expect.truthy(0)
    expect.truthy("")
    expect.falsy(nil)
    expect.falsy(false)
    expect.error(function() expect.truthy(nil) end, "expected a true value")
    expect.error(function() expect.falsy(1) end, "expected false or nil")
  end)

  it("error checks the message against a pattern or plain text", function()
    expect.error(function() error("boom 42") end, "boom %d+")
    expect.error(function() error("a (literal) match") end, "(literal)")
    expect.error(function() expect.error(function() end) end, "expected an error")
    expect.error(function() expect.error(function() error("other") end, "boom") end, "matching")
  end)

  it("near allows a margin", function()
    expect.near(0.1 + 0.2, 0.3)
    expect.near(10, 10.4, 0.5)
    expect.error(function() expect.near(10, 11, 0.5) end)
  end)

  it("contains finds list items deeply and substrings", function()
    expect.contains({ "a", "b" }, "b")
    expect.contains({ { 1, 2 }, { 3 } }, { 3 })
    expect.contains("hello world", "o w")
    expect.error(function() expect.contains({ "a" }, "z") end, "to contain")
  end)

  it("adds the optional message in front of the failure", function()
    local err = expect.error(function() expect.equal(1, 2, "slot count") end)
    expect.contains(err, "slot count: expected 2, got 1")
  end)

  it("assert is callable and has the expectations", function()
    assert(true)
    assert.equal("a", "a")
    expect.error(function() assert(false, "nope") end, "nope")
  end)
end)

describe("hooks", function()
  local log = {}
  before_each(function() table.insert(log, "outer") end)
  describe("nested", function()
    before_each(function() table.insert(log, "inner") end)
    after_each(function() table.insert(log, "after") end)
    it("runs outer before inner", function()
      expect.same(log, { "outer", "inner" })
    end)
  end)
  it("runs after_each and only the hooks around the test", function()
    expect.same(log, { "outer", "inner", "after", "outer" })
  end)
end)

describe("stub", function()
  local original = string.rep
  it("replaces a field for one test", function()
    testing.stub(string, "rep", function() return "stubbed" end)
    expect.equal(string.rep("x", 3), "stubbed")
  end)
  it("is put back afterwards", function()
    expect.equal(string.rep, original)
  end)
end)

describe("fakeTurtle", function()
  it("plays scripted results in order and repeats the last", function()
    local t = testing.fakeTurtle({ detect = { true, false } })
    expect.same({ t.detect(), t.detect(), t.detect() }, { true, false, false })
    expect.equal(t.called("detect"), 3)
  end)

  it("returns several values with returns()", function()
    local t = testing.fakeTurtle({ dig = testing.returns(false, "Unbreakable block detected") })
    local ok, why = t.dig()
    expect.falsy(ok)
    expect.equal(why, "Unbreakable block detected")
  end)

  it("calls scripted functions with the fake and the arguments", function()
    local t = testing.fakeTurtle({ inspect = function(fake, ...) return true, { name = "minecraft:stone", n = select("#", ...) } end })
    local ok, block = t.inspect()
    expect.truthy(ok)
    expect.equal(block.name, "minecraft:stone")
  end)

  it("tracks moves, turns and fuel by default", function()
    local t = testing.fakeTurtle({ fuel = 3 })
    t.forward(); t.turnRight(); t.forward(); t.up()
    expect.same({ t.x, t.y, t.z, t.heading, t.fuel }, { 1, 1, 1, 1, 0 })
    local ok, why = t.forward()
    expect.falsy(ok)
    expect.equal(why, "Out of fuel")
    expect.same(t.names(testing.actionsOnly), { "forward", "turnRight", "forward", "up", "forward" })
  end)

  it("keeps an inventory and records drops", function()
    local t = testing.fakeTurtle({ slots = { [2] = { name = "minecraft:coal", count = 10 } } })
    expect.equal(t.getItemCount(2), 10)
    t.select(2)
    expect.truthy(t.refuel(1))
    expect.equal(t.fuel, 1080)
    expect.truthy(t.drop(4))
    expect.same(t.dropped, { { name = "minecraft:coal", count = 4, dir = "" } })
    expect.same(t.getItemDetail(), { name = "minecraft:coal", count = 5 })
    expect.error(function() t.select(17) end, "out of range")
  end)

  it("can stand in for the global turtle", function()
    local fake = testing.useTurtle(testing.fakeTurtle())
    expect.equal(turtle, fake)
  end)
end)
