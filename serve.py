#!/usr/bin/env python3
"""Host this repo over plain HTTP so ComputerCraft computers can wget it.

Run on your local machine:

    python3 serve.py              # serves on 0.0.0.0:8080
    python3 serve.py -p 9000      # other port

Then on a computer or turtle in game:

    wget run http://<host>:<port>/install.lua

That downloads every .lua file in the repo into the same paths on the
computer and saves the installer as /update.lua, so later you can just run
"update" to pull the latest files again.

Individual files are also available, e.g.:

    wget http://<host>:<port>/programs/turtle/stripmine.lua programs/turtle/stripmine.lua

Only needs the Python standard library.
"""

import argparse
import os
import socket
import sys
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer

# Paths (relative to the repo root) that are never served or listed.
EXCLUDED_DIRS = {".git", "__pycache__"}
EXCLUDED_FILES = {"serve.py"}
# Only files with these extensions go into the installer manifest.
MANIFEST_EXTENSIONS = {".lua"}

INSTALLER_TEMPLATE = r"""-- Generated by serve.py. Fetches every file in the manifest below from
-- the server that produced this script.
--
-- Usage: install [baseurl]
local base = ...
if not base or base == "" then base = "{base_url}" end
if base:sub(-1) ~= "/" then base = base .. "/" end

local files = {{
{file_list}
}}

local function fetch(url)
  local r, err = http.get(url)
  if not r then return nil, err end
  local code = r.getResponseCode()
  local data = r.readAll()
  r.close()
  if code ~= 200 then return nil, "HTTP " .. tostring(code) end
  return data
end

local function save(path, data)
  local dir = fs.getDir(path)
  if dir ~= "" and not fs.exists(dir) then fs.makeDir(dir) end
  local h = fs.open(path, "w")
  if not h then return false end
  h.write(data)
  h.close()
  return true
end

local ok, failed = 0, 0
for _, file in ipairs(files) do
  io.write("fetching " .. file .. " ... ")
  local data, err = fetch(base .. file)
  if data and save(file, data) then
    ok = ok + 1
    print("ok")
  else
    failed = failed + 1
    print("FAILED (" .. tostring(err or "write error") .. ")")
  end
end

-- Keep a copy of this installer so "update" re-fetches everything later.
local self, err = fetch(base .. "install.lua")
if self then save("update.lua", self) end

print(string.format("%d fetched, %d failed from %s", ok, failed, base))
if failed == 0 then
  print("Reboot (or run startup) to load the new APIs.")
end
"""


def manifest(root):
    """Return the sorted list of files to put in the installer."""
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDED_DIRS and not d.startswith("."))
        for name in filenames:
            if name in EXCLUDED_FILES or name.startswith("."):
                continue
            if os.path.splitext(name)[1] not in MANIFEST_EXTENSIONS:
                continue
            rel = os.path.relpath(os.path.join(dirpath, name), root)
            found.append(rel.replace(os.sep, "/"))
    return sorted(found)


def render_installer(root, base_url):
    files = manifest(root)
    file_list = "\n".join('  "%s",' % f for f in files)
    return INSTALLER_TEMPLATE.format(base_url=base_url, file_list=file_list)


class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=SERVE_ROOT, **kwargs)

    def _base_url(self):
        host = self.headers.get("Host") or "%s:%d" % self.server.server_address[:2]
        return "http://%s/" % host

    def _send_text(self, body):
        data = body.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(data)

    def do_GET(self):
        path = self.path.split("?", 1)[0]
        if path in ("/", "/install.lua", "/update.lua"):
            return self._send_text(render_installer(SERVE_ROOT, self._base_url()))
        if path == "/files.txt":
            return self._send_text("\n".join(manifest(SERVE_ROOT)) + "\n")
        parts = path.strip("/").split("/")
        if any(p in EXCLUDED_DIRS or p in EXCLUDED_FILES or p.startswith(".") for p in parts):
            return self.send_error(404)
        return super().do_GET()

    do_HEAD = do_GET

    def end_headers(self):
        # Always serve lua as plain text; CC does not care but browsers do.
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def log_message(self, fmt, *args):
        sys.stderr.write("%s %s\n" % (self.address_string(), fmt % args))


def local_ips():
    ips = set()
    try:
        for info in socket.getaddrinfo(socket.gethostname(), None, socket.AF_INET):
            ips.add(info[4][0])
    except socket.gaierror:
        pass
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("10.255.255.255", 1))
        ips.add(s.getsockname()[0])
        s.close()
    except OSError:
        pass
    return sorted(ip for ip in ips if not ip.startswith("127."))


def main():
    global SERVE_ROOT
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("-p", "--port", type=int, default=8080)
    parser.add_argument("-b", "--bind", default="0.0.0.0", help="address to listen on (default: all)")
    parser.add_argument("-d", "--dir", default=os.path.dirname(os.path.abspath(__file__)),
                        help="directory to serve (default: this repo)")
    args = parser.parse_args()
    SERVE_ROOT = os.path.abspath(args.dir)

    files = manifest(SERVE_ROOT)
    server = ThreadingHTTPServer((args.bind, args.port), Handler)
    print("Serving %d lua files from %s" % (len(files), SERVE_ROOT), flush=True)
    print("In game, run one of:")
    for ip in local_ips() or ["<this machine's ip>"]:
        print("  wget run http://%s:%d/install.lua" % (ip, args.port))
    print("Ctrl+C to stop.", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


SERVE_ROOT = os.path.dirname(os.path.abspath(__file__))

if __name__ == "__main__":
    main()
